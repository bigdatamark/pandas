# [PACKAGE DOC]
# Subpackage of the benchmark suite holding benchmarks for pandas input and output:
# reading and writing text, spreadsheet, hierarchical, JSON, pickle, SAS, SQL and
# Stata formats, plus parser comparisons and styler rendering. Submodules: csv,
# excel, hdf, json, parsers, pickle, sas, sql, stata and style. This package
# re-exports nothing and has no import-time side effects. Most benchmark classes
# inside derive from the shared file-benchmark base class in the parent package's
# common helper module, which removes the temporary file after each run.
