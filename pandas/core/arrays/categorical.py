    def _cast_pointwise_result(self, values) -> ArrayLike:
        # [FUNCTION DOC]
        # HELPER: post-processes the result of an element-wise operation.
        # Parameter values is the raw result array. Defers to the parent
        # conversion, then tries to rebuild a categorical with this array's dtype
        # (silencing the warning about values outside the categories). If the
        # rebuilt array has missing values exactly where the result does (no
        # value was lost), returns it; otherwise returns the parent's result.
        res = super()._cast_pointwise_result(values)
        with warnings.catch_warnings():
            warnings.filterwarnings(
                "ignore",
                "Constructing a Categorical with a dtype and values containing",
            )
            cat = type(self)._from_sequence(res, dtype=self.dtype)
        if (cat.isna() == isna(res)).all():
            # i.e. the conversion was non-lossy
            return cat
        return res

