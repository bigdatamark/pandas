    def _validate_setitem_value(self, value):
        # [FUNCTION DOC]
        # HELPER: converts a value being assigned into codes. Parameter value is
        # a scalar or list-like. Non-hashable values (lists, arrays) go through
        # the list-like validator; hashable values (including hashable
        # sequences such as tuples treated as scalars) go through the scalar
        # validator. Returns the code or codes; raises a type error for values
        # outside the categories.
        if not is_hashable(value):
            # wrap scalars and hashable-listlikes in list
            return self._validate_listlike(value)
        else:
            return self._validate_scalar(value)

    def _validate_scalar(self, fill_value):
        # [FUNCTION DOC]
        # HELPER: converts one user value to a stored code. Parameter fill_value is
        # any object. A value that counts as missing for the categories' dtype
        # becomes minus one; a value among the categories becomes its code;
        # anything else raises a type error telling the user to set the
        # categories first. Returns the integer code.
        """
        Convert a user-facing fill_value to a representation to use with our
        underlying ndarray, raising TypeError if this is not possible.

        Parameters
        ----------
        fill_value : object

        Returns
        -------
        fill_value : int

        Raises
        ------
        TypeError
        """

        if is_valid_na_for_dtype(fill_value, self.categories.dtype):
            fill_value = -1
        elif fill_value in self.categories:
            fill_value = self._unbox_scalar(fill_value)
        else:
            raise TypeError(
                "Cannot setitem on a Categorical with a new "
                f"category ({fill_value}), set the categories first"
            ) from None
        return fill_value

    @classmethod
    def _validate_codes_for_dtype(cls, codes, *, dtype: CategoricalDtype) -> np.ndarray:
        # [FUNCTION DOC]
        # HELPER (class method): validates user-provided codes. Parameters: codes
        # is an array-like of integers; dtype (keyword) is a categorical dtype
        # with categories. Nullable integer arrays are converted to 64-bit
        # integers (raising a value error if they contain missing values);
        # anything else becomes a numpy array. Raises a value error if a
        # non-empty array is not integer/unsigned, or if any code is at least the
        # number of categories or below minus one. Returns the numpy array.
        if isinstance(codes, ExtensionArray) and is_integer_dtype(codes.dtype):
            # Avoid the implicit conversion of Int to object
            if isna(codes).any():
                raise ValueError("codes cannot contain NA values")
            codes = codes.to_numpy(dtype=np.int64)
        else:
            codes = np.asarray(codes)
        if len(codes) and codes.dtype.kind not in "iu":
            raise ValueError("codes need to be array-like integers")

        if len(codes) and (codes.max() >= len(dtype.categories) or codes.min() < -1):
            raise ValueError("codes need to be between -1 and len(categories)-1")
        return codes

