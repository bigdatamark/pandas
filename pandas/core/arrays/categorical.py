def _get_codes_for_values(
    values: Index | Series | ExtensionArray | np.ndarray,
    categories: Index,
) -> np.ndarray:
    # [FUNCTION DOC]
    # HELPER: converts raw values to codes for a given category index.
    # Parameters: values is an index, series, extension array or numpy array
    # (not categorical, which should use the recode helper); categories is the
    # category index. Looks each value up in the categories; non-missing values
    # that are not found produce a deprecation warning (Pandas 4 warning class)
    # and become code minus one. Returns the codes narrowed to the smallest
    # suitable integer type.
    """
    utility routine to turn values into codes given the specified categories

    If `values` is known to be a Categorical, use recode_for_categories instead.
    """
    codes = categories.get_indexer_for(values)
    wrong = (codes == -1) & ~isna(values)
    if wrong.any():
        warnings.warn(
            "Constructing a Categorical with a dtype and values containing "
            "non-null entries not in that dtype's categories is deprecated "
            "and will raise in a future version.",
            Pandas4Warning,
            stacklevel=find_stack_level(),
        )
    return coerce_indexer_dtype(codes, categories)


def recode_for_categories(
    codes: np.ndarray,
    old_categories,
    new_categories,
    *,
    copy: bool = True,
    warn: bool = False,
) -> np.ndarray:
    # [FUNCTION DOC]
    # Translates integer codes from one category set to another. Parameters:
    # codes is an integer array; old_categories and new_categories are indexes;
    # copy (keyword, default true) controls whether unchanged codes are copied;
    # warn (keyword, default false) emits a deprecation warning (Pandas 4 warning
    # class) when some old category is absent from the new ones. If there are
    # no old categories or both indexes are equal the codes are returned as is
    # (copied if requested). Otherwise each old category is looked up in the new
    # index and codes are mapped through that table, with unmatched and
    # missing codes becoming minus one. Returns the new codes (narrowed to a
    # suitable integer type).
    # KNOWN ISSUE: the docstring says the result is 64-bit integers, but the
    # codes are narrowed to the smallest type that fits the new categories (the
    # example in the docstring shows 8-bit).
    """
    Convert a set of codes for to a new set of categories

    Parameters
    ----------
    codes : np.ndarray
    old_categories, new_categories : Index
    copy: bool, default True
        Whether to copy if the codes are unchanged.
    warn : bool, default False
        Whether to warn on silent-NA mapping.

    Returns
    -------
    new_codes : np.ndarray[np.int64]

    Examples
    --------
    >>> old_cat = pd.Index(["b", "a", "c"])
    >>> new_cat = pd.Index(["a", "b"])
    >>> codes = np.array([0, 1, 1, 2])
    >>> recode_for_categories(codes, old_cat, new_cat, copy=True)
    array([ 1,  0,  0, -1], dtype=int8)
    """
    if len(old_categories) == 0:
        # All null anyway, so just retain the nulls
        if copy:
            return codes.copy()
        return codes
    elif new_categories.equals(old_categories):
        # Same categories, so no need to actually recode
        if copy:
            return codes.copy()
        return codes

    codes_in_old_cats = new_categories.get_indexer_for(old_categories)
    if warn:
        wrong = codes_in_old_cats == -1
        if wrong.any():
            warnings.warn(
                "Constructing a Categorical with a dtype and values containing "
                "non-null entries not in that dtype's categories is deprecated "
                "and will raise in a future version.",
                Pandas4Warning,
                stacklevel=find_stack_level(),
            )
    indexer = coerce_indexer_dtype(codes_in_old_cats, new_categories)
    new_codes = take_nd(indexer, codes, fill_value=-1)
    return new_codes


def factorize_from_iterable(values) -> tuple[np.ndarray, Index]:
    # [FUNCTION DOC]
    # Splits a list-like into integer codes and the categories index. Parameter
    # values must be list-like (type error otherwise). For categorical input the
    # categories are returned as a categorical index that keeps category order
    # and the dtype, and the codes are the existing codes. For anything else a
    # categorical is built (unordered) and its codes and categories returned.
    # Returns the pair (codes, categories).
    """
    Factorize an input `values` into `categories` and `codes`. Preserves
    categorical dtype in `categories`.

    Parameters
    ----------
    values : list-like

    Returns
    -------
    codes : ndarray
    categories : Index
        If `values` has a categorical dtype, then `categories` is
        a CategoricalIndex keeping the categories and order of `values`.
    """
    from pandas import CategoricalIndex

    if not is_list_like(values):
        raise TypeError("Input must be list-like")

    categories: Index

    vdtype = getattr(values, "dtype", None)
    if isinstance(vdtype, CategoricalDtype):
        values = extract_array(values)
        # The Categorical we want to build has the same categories
        # as values but its codes are by def [0, ..., len(n_categories) - 1]
        cat_codes = np.arange(len(values.categories), dtype=values.codes.dtype)
        cat = Categorical.from_codes(cat_codes, dtype=values.dtype, validate=False)

        categories = CategoricalIndex(cat)
        codes = values.codes
    else:
        # The value of ordered is irrelevant since we don't use cat as such,
        # but only the resulting categories, the order of which is independent
        # from ordered. Set ordered to False as default. See GH #15457
        cat = Categorical(values, ordered=False)
        categories = cat.categories
        codes = cat.codes
    return codes, categories


def factorize_from_iterables(iterables) -> tuple[list[np.ndarray], list[Index]]:
    # [FUNCTION DOC]
    # Applies the single-iterable factorization to each item of a collection.
    # Parameter iterables is a list-like of list-likes. An empty collection
    # returns two empty lists. Otherwise returns a pair of lists: the codes
    # arrays and the categories indexes, in input order.
    """
    A higher-level wrapper over `factorize_from_iterable`.

    Parameters
    ----------
    iterables : list-like of list-likes

    Returns
    -------
    codes : list of ndarrays
    categories : list of Indexes

    Notes
    -----
    See `factorize_from_iterable` for more info.
    """
    if len(iterables) == 0:
        # For consistency, it should return two empty lists.
        return [], []

    codes, categories = zip(
        *(factorize_from_iterable(it) for it in iterables),
        strict=True,
    )
    return list(codes), list(categories)
