    def _get_repr_footer(self) -> str:
        # [FUNCTION DOC]
        # HELPER: builds the "Categories (count, dtype): [...]" footer line(s).
        # Categories are joined with a less-than separator when ordered and a
        # comma otherwise, wrapped onto new lines (indented under the bracket)
        # when exceeding the display width option (or terminal width); in
        # notebook frontends no wrapping is done. An ellipsis in the middle of
        # an ordered listing is collapsed. Returns the footer string.
        """
        Returns a string representation of the footer.
        """
        category_strs = self._repr_categories()
        dtype = str(self.categories.dtype)
        levheader = f"Categories ({len(self.categories)}, {dtype}): "
        width, _ = get_terminal_size()
        max_width = get_option("display.width") or width
        if console.in_ipython_frontend():
            # 0 = no breaks
            max_width = 0
        levstring = ""
        start = True
        cur_col_len = len(levheader)  # header
        sep_len, sep = (3, " < ") if self.ordered else (2, ", ")
        linesep = f"{sep.rstrip()}\n"  # remove whitespace
        for val in category_strs:
            if max_width != 0 and cur_col_len + sep_len + len(val) > max_width:
                levstring += linesep + (" " * (len(levheader) + 1))
                cur_col_len = len(levheader) + 1  # header + a whitespace
            elif not start:
                levstring += sep
                cur_col_len += len(val)
            levstring += val
            start = False
        # replace to simple save space by
        return f"{levheader}[{levstring.replace(' < ... < ', ' ... ')}]"

    def _get_values_repr(self) -> str:
        # [FUNCTION DOC]
        # HELPER: formats the values as a bracketed, comma-separated string.
        # Requires a non-empty array (asserted). Values are formatted with
        # quoting of non-numeric entries and "NaN" for missing, stripped, and
        # joined. Returns the string.
        from pandas.io.formats import format as fmt

        assert len(self) > 0

        vals = self._internal_get_values()
        fmt_values = fmt.format_array(
            vals,
            None,
            float_format=None,
            na_rep="NaN",
            quoting=QUOTE_NONNUMERIC,
        )

        fmt_values = [i.strip() for i in fmt_values]
        joined = ", ".join(fmt_values)
        result = "[" + joined + "]"
        return result

    def __repr__(self) -> str:
        # [FUNCTION DOC]
        # Text representation: the values, optional length line, and the
        # categories footer. Up to ten elements are shown fully; longer arrays
        # show the first five and last five with an ellipsis, followed by a
        # "Length" line, then the footer. An empty array is shown as empty
        # brackets, a comma, and the footer on one line. Returns a string.
        """
        String representation.
        """
        footer = self._get_repr_footer()
        length = len(self)
        max_len = 10
        if length > max_len:
            # In long cases we do not display all entries, so we add Length
            #  information to the __repr__.
            num = max_len // 2
            head = self[:num]._get_values_repr()
            tail = self[-(max_len - num) :]._get_values_repr()
            body = f"{head[:-1]}, ..., {tail[1:]}"
            length_info = f"Length: {len(self)}"
            result = f"{body}\n{length_info}\n{footer}"
        elif length > 0:
            body = self._get_values_repr()
            result = f"{body}\n{footer}"
        else:
            # In the empty case we use a comma instead of newline to get
            #  a more compact __repr__
            body = "[]"
            result = f"{body}, {footer}"

        return result

