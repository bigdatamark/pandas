    # String methods interface
    def _str_map(
        self, f, na_value=lib.no_default, dtype=np.dtype("object"), convert: bool = True
    ):
        # [FUNCTION DOC]
        # HELPER: string-method engine for the categorical (backs the string
        # accessor). Parameters: f is the function applied to each string;
        # na_value is the replacement for missing results (default: unspecified
        # sentinel); dtype is the result dtype (default object); convert is
        # accepted but unused. The function is applied once to the categories
        # (string-dtype categories use their own mapper; others are converted to
        # a numpy-backed extension array first) and results are gathered by code,
        # filling missing codes with na_value. For not-a-number string
        # categories and a boolean result dtype, a missing na_value becomes
        # false. Returns an array of the results.
        # KNOWN ISSUE: the convert parameter is never used.
        # Optimization to apply the callable `f` to the categories once
        # and rebuild the result by `take`ing from the result with the codes.
        # Returns the same type as the object-dtype implementation though.
        categories = self.categories
        codes = self.codes
        if categories.dtype == "string":
            result = categories.array._str_map(f, na_value, dtype)  # type: ignore[attr-defined]
            if (
                categories.dtype.na_value is np.nan  # type: ignore[union-attr]
                and is_bool_dtype(dtype)
                and (na_value is lib.no_default or isna(na_value))
            ):
                # NaN propagates as False for functions with boolean return type
                na_value = False
        else:
            from pandas.core.arrays import NumpyExtensionArray

            result = NumpyExtensionArray(categories.to_numpy())._str_map(
                f, na_value, dtype
            )
        return take_nd(result, codes, fill_value=na_value)

    def _str_get_dummies(self, sep: str = "|", dtype: NpDtype | None = None):
        # [FUNCTION DOC]
        # HELPER: dummy-variable string method. Parameters: sep (default a
        # vertical bar) separates multiple labels in one string; dtype is the
        # result dtype. Because the separator may occur inside categories, the
        # categories shortcut is not used: values are converted to strings
        # (missing as the text "NaN") and handled by the numpy-backed string
        # implementation. Returns what that implementation returns.
        # sep may not be in categories. Just bail on this.
        from pandas.core.arrays import NumpyExtensionArray

        return NumpyExtensionArray(self.to_numpy(str, na_value="NaN"))._str_get_dummies(
            sep, dtype
        )

