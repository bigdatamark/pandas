    def equals(self, other: object) -> bool:
        # [FUNCTION DOC]
        # Equality of contents. Parameter other is any object. False unless it is
        # a categorical whose dtype matches up to category order; then other is
        # re-encoded in this array's category order and the codes compared for
        # equality. Returns a boolean.
        """
        Returns True if categorical arrays are equal.

        Parameters
        ----------
        other : `Categorical`

        Returns
        -------
        bool
        """
        if not isinstance(other, Categorical):
            return False
        elif self._categories_match_up_to_permutation(other):
            other = self._encode_with_my_categories(other)
            return np.array_equal(self._codes, other._codes)
        return False

    def _accumulate(self, name: str, skipna: bool = True, **kwargs) -> Self:
        # [FUNCTION DOC]
        # HELPER: running minimum/maximum by category order. Parameters: name must
        # be the cumulative-minimum or cumulative-maximum name (else a type
        # error); skipna (default true); extra keyword arguments are ignored.
        # Requires an ordered categorical (type error otherwise). Works on a copy
        # of the codes: for the minimum, missing codes are temporarily set to the
        # largest representable code so they never win; the accumulation runs;
        # missing positions (and, when not skipping, everything after the first
        # missing) are set back to missing. Returns a new categorical with the
        # same dtype.
        func: Callable
        if name == "cummin":
            func = np.minimum.accumulate
        elif name == "cummax":
            func = np.maximum.accumulate
        else:
            raise TypeError(f"Accumulation {name} not supported for {type(self)}")
        self.check_for_ordered(name)

        codes = self.codes.copy()
        mask = self.isna()
        if func == np.minimum.accumulate:
            codes[mask] = np.iinfo(codes.dtype.type).max
        # no need to change codes for maximum because codes[mask] is already -1
        if not skipna:
            mask = np.maximum.accumulate(mask)

        codes = func(codes)
        codes[mask] = -1
        return self._simple_new(codes, dtype=self._dtype)

    @classmethod
    def _concat_same_type(cls, to_concat: Sequence[Self], axis: AxisInt = 0) -> Self:
        # [FUNCTION DOC]
        # Class method concatenating categoricals. Parameters: to_concat is a
        # non-empty sequence of categoricals; axis (default 0). Raises a value
        # error if the axis is out of bounds for the first element. Along axis 1
        # (two-dimensional input; all must be two-dimensional else a bare value
        # error) each column is split off, concatenated along axis 0, and
        # reshaped back in column-major order. Axis 0 uses the categorical union
        # helper, which unions categories. Returns the concatenated categorical.
        from pandas.core.dtypes.concat import union_categoricals

        first = to_concat[0]
        if axis >= first.ndim:
            raise ValueError(
                f"axis {axis} is out of bounds for array of dimension {first.ndim}"
            )

        if axis == 1:
            # Flatten, concatenate then reshape
            if not all(x.ndim == 2 for x in to_concat):
                raise ValueError

            # pass correctly-shaped to union_categoricals
            tc_flat = []
            for obj in to_concat:
                tc_flat.extend([obj[:, i] for i in range(obj.shape[1])])

            res_flat = cls._concat_same_type(tc_flat, axis=0)

            result = res_flat.reshape(len(first), -1, order="F")
            return result

        # error: Incompatible types in assignment (expression has type "Categorical",
        # variable has type "Self")
        result = union_categoricals(to_concat)  # type: ignore[assignment]
        return result

    # ------------------------------------------------------------------

    def _encode_with_my_categories(self, other: Categorical) -> Categorical:
        # [FUNCTION DOC]
        # HELPER: re-expresses another categorical's codes in this array's
        # category order. Parameter other must have matching categories up to
        # permutation (assumed checked by the caller). Returns a categorical with
        # this array's dtype holding the recoded values.
        """
        Re-encode another categorical using this Categorical's categories.

        Notes
        -----
        This assumes we have already checked
        self._categories_match_up_to_permutation(other).
        """
        # Indexing on codes is more efficient if categories are the same,
        #  so we can apply some optimizations based on the degree of
        #  dtype-matching.
        codes = recode_for_categories(
            other.codes, other.categories, self.categories, copy=False
        )
        return self._from_backing_data(codes)

    def _categories_match_up_to_permutation(self, other: Categorical) -> bool:
        # [FUNCTION DOC]
        # HELPER: checks whether two categoricals share the same category set and
        # orderedness irrespective of listed category order for unordered ones.
        # Parameter other is a categorical. Implemented by comparing the hash
        # values of the two dtypes. Returns a boolean.
        # KNOWN ISSUE: relies on hash equality alone, so a hash collision between
        # different dtypes would be reported as a match; the docstring also
        # describes the check as "same categories" without mentioning the
        # permutation-insensitivity for unordered dtypes.
        """
        Returns True if categoricals are the same dtype
          same categories, and same ordered

        Parameters
        ----------
        other : Categorical

        Returns
        -------
        bool
        """
        return hash(self.dtype) == hash(other.dtype)

    def describe(self) -> DataFrame:
        # [FUNCTION DOC]
        # Summarizes category frequencies. Takes no arguments. Counts every
        # category including missing (as a final entry), computes relative
        # frequencies as each count divided by the total, and joins them
        # side by side. Returns a table with columns "counts" and "freqs", whose
        # index is named "categories" (the index is a default integer index
        # from the concatenation step with ignore-index semantic applied to
        # columns, so row labels come from the counts' index).
        """
        Describes this Categorical

        Returns
        -------
        description: `DataFrame`
            A dataframe with frequency and counts by category.
        """
        counts = self.value_counts(dropna=False)
        freqs = counts / counts.sum()

        from pandas import Index
        from pandas.core.reshape.concat import concat

        result = concat([counts, freqs], ignore_index=True, axis=1)
        result.columns = Index(["counts", "freqs"])
        result.index.name = "categories"

        return result

    def isin(self, values: ArrayLike) -> npt.NDArray[np.bool_]:
        # [FUNCTION DOC]
        # Membership test per element. Parameter values is an array-like of
        # values to look for. Looks up each value in the categories, keeps the
        # codes found (and codes for missing entries in values), and tests the
        # codes of this array for membership in them, so missing elements match
        # only if values contains a missing entry. Returns a boolean array.
        # Passing a bare string raises a type error (from the generic lookup).
        """
        Check whether `values` are contained in Categorical.

        Return a boolean NumPy Array showing whether each element in
        the Categorical matches an element in the passed sequence of
        `values` exactly.

        Parameters
        ----------
        values : np.ndarray or ExtensionArray
            The sequence of values to test. Passing in a single string will
            raise a ``TypeError``. Instead, turn a single string into a
            list of one element.

        Returns
        -------
        np.ndarray[bool]

        Raises
        ------
        TypeError
          * If `values` is not a set or list-like

        See Also
        --------
        pandas.Series.isin : Equivalent method on Series.

        Examples
        --------
        >>> s = pd.Categorical(["llama", "cow", "llama", "beetle", "llama", "hippo"])
        >>> s.isin(["cow", "llama"])
        array([ True,  True,  True, False,  True, False])

        Passing a single string as ``s.isin('llama')`` will raise an error. Use
        a list of one element instead:

        >>> s.isin(["llama"])
        array([ True, False,  True, False,  True, False])
        """
        null_mask = np.asarray(isna(values))
        code_values = self.categories.get_indexer_for(values)
        code_values = code_values[null_mask | (code_values >= 0)]
        return algorithms.isin(self.codes, code_values)

