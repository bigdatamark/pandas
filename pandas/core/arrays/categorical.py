    def _set_categories(self, categories, fastpath: bool = False) -> None:
        # [FUNCTION DOC]
        # HELPER: replaces the categories in place without touching codes
        # (a rename). Parameters: categories is an index-like; fastpath (default
        # false) skips validation of uniqueness and missing values. Builds a new
        # dtype with the same ordered flag; when not on the fast path and the
        # array already has categories, raises a value error if the new count
        # differs from the old. Re-initializes the array object with the same
        # codes and the new dtype. Mutates self; returns nothing.
        """
        Sets new categories inplace

        Parameters
        ----------
        fastpath : bool, default False
           Don't perform validation of the categories for uniqueness or nulls

        Examples
        --------
        >>> c = pd.Categorical(["a", "b"])
        >>> c
        ['a', 'b']
        Categories (2, str): ['a', 'b']

        >>> c._set_categories(pd.Index(["a", "c"]))
        >>> c
        ['a', 'c']
        Categories (2, str): ['a', 'c']
        """
        if fastpath:
            new_dtype = CategoricalDtype._from_fastpath(categories, self.ordered)
        else:
            new_dtype = CategoricalDtype(categories, ordered=self.ordered)
        if (
            not fastpath
            and self.dtype.categories is not None
            and len(new_dtype.categories) != len(self.dtype.categories)
        ):
            raise ValueError(
                "new categories need to have the same number of "
                "items as the old categories!"
            )

        super().__init__(self._ndarray, new_dtype)

    def _set_dtype(self, dtype: CategoricalDtype, *, copy: bool) -> Self:
        # [FUNCTION DOC]
        # HELPER: returns a new categorical expressed in the given dtype.
        # Parameters: dtype is a valid categorical dtype with categories (no
        # validation here); copy (keyword) says whether the recoding step must
        # copy the codes. Values whose category is absent from the new
        # categories become missing. Returns the new categorical.
        """
        Internal method for directly updating the CategoricalDtype

        Parameters
        ----------
        dtype : CategoricalDtype

        Notes
        -----
        We don't do any validation here. It's assumed that the dtype is
        a (valid) instance of `CategoricalDtype`.
        """
        codes = recode_for_categories(
            self.codes, self.categories, dtype.categories, copy=copy
        )
        return type(self)._simple_new(codes, dtype=dtype)

