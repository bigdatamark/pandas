    def astype(self, dtype: AstypeArg, copy: bool = True) -> ArrayLike:
        # [FUNCTION DOC]
        # Converts to another dtype. Parameters: dtype is anything resolvable to
        # a dtype; copy (default true) forces a new object (false may return self
        # when the dtype is the identical categorical dtype). Cases: identical
        # dtype object returns self or a copy; another categorical dtype is
        # merged with the current one, values are recoded, and a deprecation
        # warning (the Pandas 4 warning class) is emitted if non-missing values
        # fall outside the new categories (they become missing); other
        # extension dtypes defer to the parent; integer targets with any missing
        # value raise a value error; empty data or no categories go through
        # numpy conversion; otherwise the categories are converted to the target
        # dtype (errors become a value error "cannot cast") and gathered by
        # code, filling missing with the converted missing value. Returns the
        # converted array.
        """
        Coerce this type to another dtype

        Parameters
        ----------
        dtype : numpy dtype or pandas type
        copy : bool, default True
            By default, astype always returns a newly allocated object.
            If copy is set to False and dtype is categorical, the original
            object is returned.
        """
        dtype = pandas_dtype(dtype)
        result: Categorical | np.ndarray
        if self.dtype is dtype:
            result = self.copy() if copy else self

        elif isinstance(dtype, CategoricalDtype):
            # GH 10696/18593/18630
            dtype = self.dtype.update_dtype(dtype)
            self = self.copy() if copy else self
            result = self._set_dtype(dtype, copy=False)
            wrong = result.isna() & ~self.isna()
            if wrong.any():
                warnings.warn(
                    "Constructing a Categorical with a dtype and values containing "
                    "non-null entries not in that dtype's categories is deprecated "
                    "and will raise in a future version.",
                    Pandas4Warning,
                    stacklevel=find_stack_level(),
                )

        elif isinstance(dtype, ExtensionDtype):
            return super().astype(dtype, copy=copy)

        elif dtype.kind in "iu" and self.isna().any():
            raise ValueError("Cannot convert float NaN to integer")

        elif len(self.codes) == 0 or len(self.categories) == 0:
            # For NumPy 1.x compatibility we cannot use copy=None.  And
            # `copy=False` has the meaning of `copy=None` here:
            if not copy:
                result = np.asarray(self, dtype=dtype)
            else:
                result = np.array(self, dtype=dtype)

        else:
            # GH8628 (PERF): astype category codes instead of astyping array
            new_cats = self.categories._values

            try:
                new_cats = new_cats.astype(dtype=dtype, copy=copy)
                fill_value = self.categories._na_value
                if not is_valid_na_for_dtype(fill_value, dtype):
                    fill_value = lib.item_from_zerodim(
                        np.array(self.categories._na_value).astype(dtype)
                    )
            except (
                TypeError,  # downstream error msg for CategoricalIndex is misleading
                ValueError,
            ) as err:
                msg = f"Cannot cast {self.categories.dtype} dtype to {dtype}"
                raise ValueError(msg) from err

            result = take_nd(
                new_cats, ensure_platform_int(self._codes), fill_value=fill_value
            )

        return result

    @classmethod
    def _from_inferred_categories(
        cls, inferred_categories, inferred_codes, dtype, true_values=None
    ) -> Self:
        # [FUNCTION DOC]
        # HELPER: builds a categorical from categories and codes inferred while
        # parsing (used by the text reader). Parameters: inferred_categories are
        # the category values in discovery order (typically strings);
        # inferred_codes are integer codes into them; dtype is a categorical
        # dtype (possibly without categories) or the generic category label;
        # true_values optionally lists strings meaning true (default three
        # spellings). If the dtype has known categories, the inferred ones are
        # converted to that categories' kind (numeric, datetime, time delta, or
        # boolean via membership in the true values) with invalid entries
        # becoming missing, and codes are recoded to the known order (with a
        # deprecation warning for unmatched values). Otherwise, unsorted
        # inferred categories are sorted and codes recoded, and sorted ones are
        # used as is, always unordered. Returns a new categorical.
        """
        Construct a Categorical from inferred values.

        For inferred categories (`dtype` is None) the categories are sorted.
        For explicit `dtype`, the `inferred_categories` are cast to the
        appropriate type.

        Parameters
        ----------
        inferred_categories : Index
        inferred_codes : Index
        dtype : CategoricalDtype or 'category'
        true_values : list, optional
            If none are provided, the default ones are
            "True", "TRUE", and "true."

        Returns
        -------
        Categorical
        """
        from pandas import (
            Index,
            to_datetime,
            to_numeric,
            to_timedelta,
        )

        cats = Index(inferred_categories, copy=False)
        known_categories = (
            isinstance(dtype, CategoricalDtype) and dtype.categories is not None
        )

        if known_categories:
            # Convert to a specialized type with `dtype` if specified.
            if is_any_real_numeric_dtype(dtype.categories.dtype):
                cats = to_numeric(inferred_categories, errors="coerce")
            elif lib.is_np_dtype(dtype.categories.dtype, "M"):
                cats = to_datetime(inferred_categories, errors="coerce")
            elif lib.is_np_dtype(dtype.categories.dtype, "m"):
                cats = to_timedelta(inferred_categories, errors="coerce")
            elif is_bool_dtype(dtype.categories.dtype):
                if true_values is None:
                    true_values = ["True", "TRUE", "true"]

                # error: Incompatible types in assignment (expression has type
                # "ndarray", variable has type "Index")
                cats = cats.isin(true_values)  # type: ignore[assignment]

        if known_categories:
            # Recode from observation order to dtype.categories order.
            categories = dtype.categories
            codes = recode_for_categories(
                inferred_codes, cats, categories, copy=False, warn=True
            )
        elif not cats.is_monotonic_increasing:
            # Sort categories and recode for unknown categories.
            unsorted = cats.copy()
            categories = cats.sort_values()

            codes = recode_for_categories(
                inferred_codes, unsorted, categories, copy=False, warn=True
            )
            dtype = CategoricalDtype(categories, ordered=False)
        else:
            dtype = CategoricalDtype(cats, ordered=False)
            codes = inferred_codes

        return cls._simple_new(codes, dtype=dtype)

    @classmethod
    def from_codes(
        cls,
        codes,
        categories=None,
        ordered=None,
        dtype: Dtype | None = None,
        validate: bool = True,
    ) -> Self:
        # [FUNCTION DOC]
        # Class method building a categorical from integer codes without
        # factorizing. Parameters: codes is an integer array-like (minus one for
        # missing); categories, ordered and dtype describe the categories
        # (resolved with the usual rules, dtype exclusive with the others);
        # validate (default true) checks the codes (unsafe to skip: invalid
        # codes may crash). Raises a value error if no categories are available
        # from either categories or dtype, and (via validation) for non-integer
        # or out-of-range codes. Returns a new categorical sharing no
        # validation work.
        """

        This constructor is useful if you already have codes and
        categories/dtype and so do not need the (computation intensive)
        factorization step, which is usually done on the constructor.

        If your data does not follow this convention, please use the normal
        constructor.

        Parameters
        ----------
        codes : array-like of int
            An integer array, where each integer points to a category in
            categories or dtype.categories, or else is -1 for NaN.
        categories : index-like, optional
            The categories for the categorical. Items need to be unique.
            If the categories are not given here, then they must be provided
            in `dtype`.
        ordered : bool, optional
            Whether or not this categorical is treated as an ordered
            categorical. If not given here or in `dtype`, the resulting
            categorical will be unordered.
        dtype : CategoricalDtype or "category", optional
            If :class:`CategoricalDtype`, cannot be used together with
            `categories` or `ordered`.
        validate : bool, default True
            If True, validate that the codes are valid for the dtype.
            If False, don't validate that the codes are valid. Be careful about skipping
            validation, as invalid codes can lead to severe problems, such as segfaults.

            .. versionadded:: 2.1.0

        Returns
        -------
        Categorical

        See Also
        --------
        codes : The category codes of the categorical.
        CategoricalIndex : An Index with an underlying ``Categorical``.

        Examples
        --------
        >>> dtype = pd.CategoricalDtype(["a", "b"], ordered=True)
        >>> pd.Categorical.from_codes(codes=[0, 1, 0, 1], dtype=dtype)
        ['a', 'b', 'a', 'b']
        Categories (2, str): ['a' < 'b']
        """
        dtype = CategoricalDtype._from_values_or_dtype(
            categories=categories, ordered=ordered, dtype=dtype
        )
        if dtype.categories is None:
            msg = (
                "The categories must be provided in 'categories' or "
                "'dtype'. Both were None."
            )
            raise ValueError(msg)

        if validate:
            # beware: non-valid codes may segfault
            codes = cls._validate_codes_for_dtype(codes, dtype=dtype)

        return cls._simple_new(codes, dtype=dtype)

