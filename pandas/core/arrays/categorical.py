def _cat_compare_op(op):
    # [FUNCTION DOC]
    # HELPER: factory that builds the comparison method for one operator, to be
    # assigned onto the categorical class. Parameter op is a function from the
    # standard operator module (equal, not equal, less, etc.); its name is used
    # to build the dunder name. Missing positions in results are filled with
    # true for not-equal and false otherwise. Returns the generated method (its
    # name set to the dunder name, wrapped so zero-dimensional arrays are
    # unpacked and unsupported operands defer).
    opname = f"__{op.__name__}__"
    fill_value = op is operator.ne

    @unpack_zerodim_and_defer(opname)
    def func(self, other):
        # [FUNCTION DOC]
        # HELPER: the generated comparison method. Parameters: self is the
        # categorical; other is the right operand. A list-like (non-hashable)
        # of the wrong length raises a value error. Ordering operators on an
        # unordered categorical raise a type error. Against another categorical:
        # the categories must match up to permutation (else a type error); if
        # both are unordered with differently ordered categories the other's
        # codes are recoded to self's categories; the operator is applied to the
        # codes and positions where either side is missing are set to the fill
        # value. Against a hashable scalar: if it is one of the categories the
        # operator runs on codes against its code (missing positions fixed up
        # unless the result is already correct for them), otherwise the generic
        # invalid-comparison result is returned. Against other list-likes: only
        # equal and not-equal are allowed (else a type error); datetime-like
        # extension arrays are handled by reversing the operands; otherwise
        # compares the dense values positionally. Returns a boolean array.
        hashable = is_hashable(other)
        if is_list_like(other) and len(other) != len(self) and not hashable:
            # in hashable case we may have a tuple that is itself a category
            raise ValueError("Lengths must match.")

        if not self.ordered:
            if opname in ["__lt__", "__gt__", "__le__", "__ge__"]:
                raise TypeError(
                    "Unordered Categoricals can only compare equality or not"
                )
        if isinstance(other, Categorical):
            # Two Categoricals can only be compared if the categories are
            # the same (maybe up to ordering, depending on ordered)

            msg = "Categoricals can only be compared if 'categories' are the same."
            if not self._categories_match_up_to_permutation(other):
                raise TypeError(msg)

            if not self.ordered and not self.categories.equals(other.categories):
                # both unordered and different order
                other_codes = recode_for_categories(
                    other.codes, other.categories, self.categories, copy=False
                )
            else:
                other_codes = other._codes

            ret = op(self._codes, other_codes)
            mask = (self._codes == -1) | (other_codes == -1)
            if mask.any():
                ret[mask] = fill_value
            return ret

        if hashable:
            if other in self.categories:
                i = self._unbox_scalar(other)
                ret = op(self._codes, i)

                if opname not in {"__eq__", "__ge__", "__gt__"}:
                    # GH#29820 performance trick; get_loc will always give i>=0,
                    #  so in the cases (__ne__, __le__, __lt__) the setting
                    #  here is a no-op, so can be skipped.
                    mask = self._codes == -1
                    ret[mask] = fill_value
                return ret
            else:
                return ops.invalid_comparison(self, other, op)
        else:
            # allow categorical vs object dtype array comparisons for equality
            # these are only positional comparisons
            if opname not in ["__eq__", "__ne__"]:
                raise TypeError(
                    f"Cannot compare a Categorical for op {opname} with "
                    f"type {type(other)}.\nIf you want to compare values, "
                    "use 'np.asarray(cat) <op> other'."
                )

            if isinstance(other, ExtensionArray) and needs_i8_conversion(other.dtype):
                # We would return NotImplemented here, but that messes up
                #  ExtensionIndex's wrapped methods
                return op(other, self)
            return getattr(np.array(self), opname)(np.array(other))

    func.__name__ = opname

    return func


def contains(cat, key, container) -> bool:
    # [FUNCTION DOC]
    # HELPER: shared membership test for the categorical array and the
    # categorical index. Parameters: cat is the categorical or index; key must
    # be hashable (a type error is raised by hashing otherwise); container is
    # the collection of codes to look in. Looks up the key among the categories;
    # if absent (lookup failure of key or type kind), returns false. If found,
    # returns whether its code (or, when the categories are intervals and the
    # lookup yields several positions, any of the codes) is in the container.
    # Missing values are not handled here (callers check separately).
    """
    Helper for membership check for ``key`` in ``cat``.

    This is a helper method for :method:`__contains__`
    and :class:`CategoricalIndex.__contains__`.

    Returns True if ``key`` is in ``cat.categories`` and the
    location of ``key`` in ``categories`` is in ``container``.

    Parameters
    ----------
    cat : :class:`Categorical`or :class:`categoricalIndex`
    key : a hashable object
        The key to check membership for.
    container : Container (e.g. list-like or mapping)
        The container to check for membership in.

    Returns
    -------
    is_in : bool
        True if ``key`` is in ``self.categories`` and location of
        ``key`` in ``categories`` is in ``container``, else False.

    Notes
    -----
    This method does not check for NaN values. Do that separately
    before calling this method.
    """
    hash(key)

    # get location of key in categories.
    # If a KeyError, the key isn't in categories, so logically
    #  can't be in container either.
    try:
        loc = cat.categories.get_loc(key)
    except (KeyError, TypeError):
        return False

    # loc is the location of key in categories, but also the *value*
    # for key in container. So, `key` may be in categories,
    # but still not in `container`. Example ('b' in categories,
    # but not in values):
    # 'b' in Categorical(['a'], categories=['a', 'b'])  # False
    if is_scalar(loc):
        return loc in container
    else:
        # if categories is an IntervalIndex, loc is an array.
        return any(loc_ in container for loc_ in loc)


@set_module("pandas")
class Categorical(NDArrayBackedExtensionArray, PandasObject, ObjectStringArrayMixin):
    # [CLASS DOC]
    # Categorical data array. State: the backing numpy array of small signed
    # integer codes (the integer width is chosen from the number of categories;
    # minus one marks a missing value) and a categorical dtype object holding
    # the unique categories (an index) and the ordered flag. Inherits the
    # numpy-backed extension array base (indexing, copy, take, concatenation),
    # the pandas object mixin, and string-method support. Key behaviors:
    # construction from values or from codes, changing categories (rename,
    # reorder, add, remove, set, remove unused), ordering (min, max, sort),
    # comparison operators (equality for all, ordering only when ordered),
    # value counts, mapping, unique, memory usage, string and tolist
    # conversion, and set-like operations. Invariants: codes are always valid
    # positions in the categories or minus one; categories are unique and
    # contain no missing values; categoricals are fixed-length, but their
    # category set can be replaced.
    """
    Represent a categorical variable in classic R / S-plus fashion.

    `Categoricals` can only take on a limited, and usually fixed, number
    of possible values (`categories`). In contrast to statistical categorical
    variables, a `Categorical` might have an order, but numerical operations
    (additions, divisions, ...) are not possible.

    All values of the `Categorical` are either in `categories` or `np.nan`.
    Assigning values outside of `categories` will raise a `ValueError`. Order
    is defined by the order of the `categories`, not lexical order of the
    values.

    Parameters
    ----------
    values : list-like
        The values of the categorical. If categories are given, values not in
        categories will be replaced with NaN.
    categories : Index-like (unique), optional
        The unique categories for this categorical. If not given, the
        categories are assumed to be the unique values of `values` (sorted, if
        possible, otherwise in the order in which they appear).
    ordered : bool, default False
        Whether or not this categorical is treated as an ordered categorical.
        If True, the resulting categorical will be ordered.
        An ordered categorical respects, when sorted, the order of its
        `categories` attribute (which in turn is the `categories` argument, if
        provided).
    dtype : CategoricalDtype
        An instance of ``CategoricalDtype`` to use for this categorical.
    copy : bool, default True
        Whether to copy if the codes are unchanged.

    Attributes
    ----------
    categories : Index
        The categories of this categorical.
    codes : ndarray
        The codes (integer positions, which point to the categories) of this
        categorical, read only.
    ordered : bool
        Whether or not this Categorical is ordered.
    dtype : CategoricalDtype
        The instance of ``CategoricalDtype`` storing the ``categories``
        and ``ordered``.

    Methods
    -------
    from_codes
    as_ordered
    as_unordered
    set_categories
    rename_categories
    reorder_categories
    add_categories
    remove_categories
    remove_unused_categories
    map
    __array__

    Raises
    ------
    ValueError
        If the categories do not validate.
    TypeError
        If an explicit ``ordered=True`` is given but no `categories` and the
        `values` are not sortable.

    See Also
    --------
    CategoricalDtype : Type for categorical data.
    CategoricalIndex : An Index with an underlying ``Categorical``.

    Notes
    -----
    See the `user guide
    <https://pandas.pydata.org/pandas-docs/stable/user_guide/categorical.html>`__
    for more.

    Examples
    --------
    >>> pd.Categorical([1, 2, 3, 1, 2, 3])
    [1, 2, 3, 1, 2, 3]
    Categories (3, int64): [1, 2, 3]

    >>> pd.Categorical(["a", "b", "c", "a", "b", "c"])
    ['a', 'b', 'c', 'a', 'b', 'c']
    Categories (3, str): ['a', 'b', 'c']

    Missing values are not included as a category.

    >>> c = pd.Categorical([1, 2, 3, 1, 2, 3, np.nan])
    >>> c
    [1, 2, 3, 1, 2, 3, NaN]
    Categories (3, int64): [1, 2, 3]

    However, their presence is indicated in the `codes` attribute
    by code `-1`.

    >>> c.codes
    array([ 0,  1,  2,  0,  1,  2, -1], dtype=int8)

    Ordered `Categoricals` can be sorted according to the custom order
    of the categories and can have a min and max value.

    >>> c = pd.Categorical(
    ...     ["a", "b", "c", "a", "b", "c"], ordered=True, categories=["c", "b", "a"]
    ... )
    >>> c
    ['a', 'b', 'c', 'a', 'b', 'c']
    Categories (3, str): ['c' < 'b' < 'a']
    >>> c.min()
    'c'
    """

    # For comparisons, so that numpy uses our implementation if the compare
    # ops, which raise
    __array_priority__ = 1000
    # tolist is not actually deprecated, just suppressed in the __dir__
    _hidden_attrs = PandasObject._hidden_attrs | frozenset(["tolist"])
    _typ = "categorical"

    _dtype: CategoricalDtype

    @classmethod
    # error: Argument 2 of "_simple_new" is incompatible with supertype
    # "NDArrayBacked"; supertype defines the argument type as
    # "Union[dtype[Any], ExtensionDtype]"
    def _simple_new(  # type: ignore[override]
        cls, codes: np.ndarray, dtype: CategoricalDtype
    ) -> Self:
        # [FUNCTION DOC]
        # HELPER: internal constructor from already-validated codes. Parameters:
        # codes is an integer numpy array; dtype is a categorical dtype with
        # categories. The codes are narrowed/widened to the smallest suitable
        # signed integer type for the number of categories, the dtype is
        # normalized (ordered defaults filled in), and the parent constructor
        # wraps the codes without copying or validation. Returns a new
        # categorical.
        # NB: This is not _quite_ as simple as the "usual" _simple_new
        codes = coerce_indexer_dtype(codes, dtype.categories)
        dtype = CategoricalDtype(ordered=False).update_dtype(dtype)
        return super()._simple_new(codes, dtype)

    def __init__(
        self,
        values,
        categories=None,
        ordered=None,
        dtype: Dtype | None = None,
        copy: bool = True,
    ) -> None:
        # [FUNCTION DOC]
        # Constructor. Parameters: values is a list-like of the data (otherwise a
        # type error is raised); categories is an optional unique index-like of
        # allowed values; ordered is an optional ordered flag; dtype is an
        # optional categorical dtype (mutually exclusive with categories and
        # ordered); copy (default true) says whether to copy codes when the
        # input is already categorical.
        # Behavior: resolves the dtype. Input handling: categorical input with no
        # given categories adopts its categories; ranges become a range index;
        # other non-array input is converted to a list-like (empty lists become
        # empty object arrays; multi-dimensional arrays raise a not-implemented
        # error; plain lists have their missing entries removed before inference
        # and reinserted as code minus one afterwards, without upcasting to float
        # when only missing values exist).
        # If categories are unknown: arrow dictionary-typed input uses its
        # dictionary and indices directly; otherwise values are factorized with
        # sorting (falling back to appearance order when unsortable, unless the
        # categorical is ordered, in which case a type error asks for explicit
        # categories); object-dtype series/index input keeps object categories.
        # If categories are known: categorical input is recoded (with a
        # deprecation warning if values fall outside) else codes are looked up
        # for the values (values not in the categories become missing).
        # Finally codes are narrowed to a suitable integer width and the parent
        # initializer stores codes and dtype.
        dtype = CategoricalDtype._from_values_or_dtype(
            values, categories, ordered, dtype
        )
        # At this point, dtype is always a CategoricalDtype, but
        # we may have dtype.categories be None, and we need to
        # infer categories in a factorization step further below

        if not is_list_like(values):
            # GH#38433
            raise TypeError("Categorical input must be list-like")

        # null_mask indicates missing values we want to exclude from inference.
        # This means: only missing values in list-likes (not arrays/ndframes).
        null_mask = np.array(False)

        # sanitize input
        vdtype = getattr(values, "dtype", None)
        if isinstance(vdtype, CategoricalDtype):
            if dtype.categories is None:
                dtype = CategoricalDtype(values.categories, dtype.ordered)
        elif isinstance(values, range):
            from pandas.core.indexes.range import RangeIndex

            values = RangeIndex(values)
        elif not isinstance(values, (ABCIndex, ABCSeries, ExtensionArray)):
            values = com.convert_to_list_like(values)
            if isinstance(values, list) and len(values) == 0:
                # By convention, empty lists result in object dtype:
                values = np.array([], dtype=object)
            elif isinstance(values, np.ndarray):
                if values.ndim > 1:
                    # preempt sanitize_array from raising ValueError
                    raise NotImplementedError(
                        "> 1 ndim Categorical are not supported at this time"
                    )
                values = sanitize_array(values, None)
            else:
                # i.e. must be a list
                arr = sanitize_array(values, None)
                null_mask = isna(arr)
                if null_mask.any():
                    # We remove null values here, then below will re-insert
                    #  them, grep "full_codes"
                    arr_list = [values[idx] for idx in np.where(~null_mask)[0]]

                    # GH#44900 Do not cast to float if we have only missing values
                    if arr_list or arr.dtype == "object":
                        sanitize_dtype = None
                    else:
                        sanitize_dtype = arr.dtype

                    arr = sanitize_array(arr_list, None, dtype=sanitize_dtype)
                values = arr

        if dtype.categories is None:
            if isinstance(values.dtype, ArrowDtype) and issubclass(
                values.dtype.type, CategoricalDtypeType
            ):
                from pandas import Index

                if isinstance(values, Index):
                    arr = values._data._pa_array.combine_chunks()
                else:
                    arr = extract_array(values)._pa_array.combine_chunks()
                categories = arr.dictionary.to_pandas(types_mapper=ArrowDtype)
                codes = arr.indices.to_numpy()
                dtype = CategoricalDtype(categories, values.dtype.pyarrow_dtype.ordered)
            else:
                preserve_object = False
                if isinstance(values, (ABCIndex, ABCSeries)) and values.dtype == object:
                    # GH#61778
                    preserve_object = True
                if not isinstance(values, ABCIndex):
                    # in particular RangeIndex xref test_index_equal_range_categories
                    values = sanitize_array(values, None)
                try:
                    codes, categories = factorize(values, sort=True)
                except TypeError as err:
                    codes, categories = factorize(values, sort=False)
                    if dtype.ordered:
                        # raise, as we don't have a sortable data structure and so
                        # the user should give us one by specifying categories
                        raise TypeError(
                            "'values' is not ordered, please "
                            "explicitly specify the categories order "
                            "by passing in a categories argument."
                        ) from err

                if preserve_object:
                    # GH#61778 wrap categories in an Index to prevent dtype
                    #  inference in the CategoricalDtype constructor
                    from pandas import Index

                    categories = Index(categories, dtype=object, copy=False)

                # if not preserve_obejct, we're inferring from values
                dtype = CategoricalDtype(categories, dtype.ordered)

        elif isinstance(values.dtype, CategoricalDtype):
            old_codes = extract_array(values)._codes
            codes = recode_for_categories(
                old_codes,
                values.dtype.categories,
                dtype.categories,
                copy=copy,
                warn=True,
            )

        else:
            codes = _get_codes_for_values(values, dtype.categories)

        if null_mask.any():
            # Reinsert -1 placeholders for previously removed missing values
            full_codes = -np.ones(null_mask.shape, dtype=codes.dtype)
            full_codes[~null_mask] = codes
            codes = full_codes

        dtype = CategoricalDtype(ordered=False).update_dtype(dtype)
        arr = coerce_indexer_dtype(codes, dtype.categories)
        super().__init__(arr, dtype)

