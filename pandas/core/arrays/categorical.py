    def __init__(self, data) -> None:
        # [FUNCTION DOC]
        # Constructor. Parameter data is a series (or categorical index) with a
        # categorical dtype; otherwise raises an attribute error (so the
        # accessor is unavailable). Stores the underlying categorical array, the
        # index and the name, then freezes the object against new attributes.
        self._validate(data)
        self._parent = data.values
        self._index = data.index
        self._name = data.name
        self._freeze()

    @staticmethod
    def _validate(data) -> None:
        # [FUNCTION DOC]
        # HELPER (static method): accessor availability check. Parameter data is
        # the object being wrapped. Raises an attribute error saying the
        # accessor requires the category dtype when the dtype is not
        # categorical; returns nothing otherwise.
        if not isinstance(data.dtype, CategoricalDtype):
            raise AttributeError("Can only use .cat accessor with a 'category' dtype")

