    def _values_for_rank(self) -> np.ndarray:
        # [FUNCTION DOC]
        # HELPER: converts the data to something rankable. Ordered: the codes,
        # converted to floats with not-a-number for missing when any are
        # missing. Unordered with real numeric categories: the dense values.
        # Unordered otherwise: categories are replaced by their own ranks
        # (via a rename on a copy) and the dense values of that returned.
        # Returns a numpy array.
        """
        For correctly ranking ordered categorical data. See GH#15420

        Ordered categorical data should be ranked on the basis of
        codes with -1 translated to NaN.

        Returns
        -------
        numpy.array

        """
        from pandas import Series

        if self.ordered:
            values = self.codes
            mask = values == -1
            if mask.any():
                values = values.astype("float64")
                values[mask] = np.nan
        elif is_any_real_numeric_dtype(self.categories.dtype):
            values = np.array(self)
        else:
            #  reorder the categories (so rank can use the float codes)
            #  instead of passing an object array to rank
            values = np.array(
                self.rename_categories(
                    Series(self.categories, copy=False).rank().values
                )
            )
        return values

    def _hash_pandas_object(
        self, *, encoding: str, hash_key: str, categorize: bool
    ) -> npt.NDArray[np.uint64]:
        # [FUNCTION DOC]
        # HELPER: hashing hook for the object-hashing utility. Parameters
        # (keyword only): encoding and hash_key are forwarded to the array
        # hasher; categorize is ignored (already categorical). Hashes each
        # category once and gathers by code; missing positions get the maximum
        # unsigned 64-bit value; with no categories the result is zeros before
        # masking. Returns an unsigned 64-bit array.
        """
        Hash a Categorical by hashing its categories, and then mapping the codes
        to the hashes.

        Parameters
        ----------
        encoding : str
        hash_key : str
        categorize : bool
            Ignored for Categorical.

        Returns
        -------
        np.ndarray[uint64]
        """
        # Note we ignore categorize, as we are already Categorical.
        from pandas.core.util.hashing import hash_array

        # Convert ExtensionArrays to ndarrays
        values = np.asarray(self.categories._values)
        hashed = hash_array(values, encoding, hash_key, categorize=False)

        # we have uint64, as we don't directly support missing values
        # we don't want to use take_nd which will coerce to float
        # instead, directly construct the result with a
        # max(np.uint64) as the missing value indicator
        #
        # TODO: GH#15362

        mask = self.isna()
        if len(hashed):
            result = hashed.take(self._codes)
        else:
            result = np.zeros(len(mask), dtype="uint64")

        if mask.any():
            result[mask] = lib.u8max

        return result

