    def min(self, *, skipna: bool = True, **kwargs):
        # [FUNCTION DOC]
        # Smallest value by category order. Parameters: skipna (keyword, default
        # true) ignores missing values; keyword arguments are validated against
        # numpy's accepted ones (axis must be valid for one dimension). Raises a
        # type error if the categorical is not ordered. Empty arrays return the
        # dtype's missing value. If any value is missing: with skipna and at
        # least one present value the minimum of the present codes is used,
        # otherwise returns not-a-number. Returns the category at the smallest
        # code via the reduction wrapper.
        """
        The minimum value of the object.

        Only ordered `Categoricals` have a minimum!

        Raises
        ------
        TypeError
            If the `Categorical` is not `ordered`.

        Returns
        -------
        min : the minimum of this `Categorical`, NA value if empty
        """
        nv.validate_minmax_axis(kwargs.get("axis", 0))
        nv.validate_min((), kwargs)
        self.check_for_ordered("min")

        if not len(self._codes):
            return self.dtype.na_value

        good = self._codes != -1
        if not good.all():
            if skipna and good.any():
                pointer = self._codes[good].min()
            else:
                return np.nan
        else:
            pointer = self._codes.min()
        return self._wrap_reduction_result(None, pointer)

    def max(self, *, skipna: bool = True, **kwargs):
        # [FUNCTION DOC]
        # Largest value by category order; mirrors the minimum method (ordered
        # required, empty gives the dtype's missing value, missing handling by
        # skipna) using the maximum code.
        """
        The maximum value of the object.

        Only ordered `Categoricals` have a maximum!

        Raises
        ------
        TypeError
            If the `Categorical` is not `ordered`.

        Returns
        -------
        max : the maximum of this `Categorical`, NA if array is empty
        """
        nv.validate_minmax_axis(kwargs.get("axis", 0))
        nv.validate_max((), kwargs)
        self.check_for_ordered("max")

        if not len(self._codes):
            return self.dtype.na_value

        good = self._codes != -1
        if not good.all():
            if skipna and good.any():
                pointer = self._codes[good].max()
            else:
                return np.nan
        else:
            pointer = self._codes.max()
        return self._wrap_reduction_result(None, pointer)

    def _mode(self, dropna: bool = True) -> Categorical:
        # [FUNCTION DOC]
        # HELPER: most frequent value(s). Parameter dropna (default true) excludes
        # missing values. Computes the mode of the codes (asserting the result
        # keeps the same integer type) and returns a categorical with the same
        # dtype built from the mode codes.
        codes = self._codes
        mask = None
        if dropna:
            mask = self.isna()

        res_codes, _ = algorithms.mode(codes, mask=mask)
        res_codes = cast(np.ndarray, res_codes)
        assert res_codes.dtype == codes.dtype
        res = self._from_backing_data(res_codes)
        return res

