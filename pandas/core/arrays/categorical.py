    def _validate_listlike(self, value):
        # [FUNCTION DOC]
        # HELPER: converts a list-like value being assigned into codes. Parameter
        # value is a list-like (scalar-like tuples are excluded by the caller).
        # A categorical value must have an identical dtype (same categories and
        # orderedness), else a type error; it is re-encoded in this array's
        # category order and its codes returned. Any other list-like is checked
        # against the categories: if it contains values outside the categories
        # that are not all missing, raises a type error asking to set the
        # categories first. Returns an array of codes (minus one for missing or
        # unmatched missing values) in this array's integer type.
        # NB: here we assume scalar-like tuples have already been excluded
        value = extract_array(value, extract_numpy=True)

        # require identical categories set
        if isinstance(value, Categorical):
            if self.dtype != value.dtype:
                raise TypeError(
                    "Cannot set a Categorical with another, "
                    "without identical categories"
                )
            # dtype equality implies categories_match_up_to_permutation
            value = self._encode_with_my_categories(value)
            return value._codes

        from pandas import Index

        # tupleize_cols=False for e.g. test_fillna_iterable_category GH#41914
        to_add = Index._with_infer(value, tupleize_cols=False, copy=False).difference(
            self.categories
        )

        # no assignments of values not in categories, but it's always ok to set
        # something to np.nan
        if len(to_add) and not isna(to_add).all():
            raise TypeError(
                "Cannot setitem on a Categorical with a new "
                "category, set the categories first"
            )

        codes = self.categories.get_indexer(value)
        return codes.astype(self._ndarray.dtype, copy=False)

    def _reverse_indexer(self) -> dict[Hashable, npt.NDArray[np.intp]]:
        # [FUNCTION DOC]
        # HELPER: groups positions by category. Takes no arguments. Sorts
        # positions by code using a counting-sort routine, then slices the sorted
        # positions per category using cumulative counts. Returns a dictionary
        # from each category (every category, in order, including unused ones
        # with empty arrays) to the integer positions where it occurs.
        # Missing values are not included.
        """
        Compute the inverse of a categorical, returning
        a dict of categories -> indexers.

        *This is an internal function*

        Returns
        -------
        Dict[Hashable, np.ndarray[np.intp]]
            dict of categories -> indexers

        Examples
        --------
        >>> c = pd.Categorical(list("aabca"))
        >>> c
        ['a', 'a', 'b', 'c', 'a']
        Categories (3, str): ['a', 'b', 'c']
        >>> c.categories
        Index(['a', 'b', 'c'], dtype='str')
        >>> c.codes
        array([0, 0, 1, 2, 0], dtype=int8)
        >>> c._reverse_indexer()
        {'a': array([0, 1, 4]), 'b': array([2]), 'c': array([3])}

        """
        categories = self.categories
        r, counts = libalgos.groupsort_indexer(
            ensure_platform_int(self.codes), categories.size
        )
        counts = ensure_int64(counts).cumsum()
        _result = (r[start:end] for start, end in itertools.pairwise(counts))
        return dict(zip(categories, _result, strict=True))

