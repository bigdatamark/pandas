    # GroupBy Methods

    def _groupby_op(
        self,
        *,
        how: str,
        has_dropped_na: bool,
        min_count: int,
        ngroups: int,
        ids: npt.NDArray[np.intp],
        **kwargs,
    ):
        # [FUNCTION DOC]
        # HELPER: group-wise aggregation entry point used by the groupby engine.
        # Parameters (keyword only): how is the operation name; has_dropped_na
        # says whether missing group keys were dropped; min_count is the minimum
        # non-missing count; ngroups is the number of groups; ids is the group
        # label for each row; extra keyword arguments go to the compiled
        # operation. Raises type errors for sum, product, cumulative sum/product,
        # skew, kurtosis (unsupported), for min/max/rank/index-of-min/max on
        # unordered data, and for any operation outside the supported list
        # (rank, any, all, first, last, min, max, index-of-min/max) with wording
        # depending on whether it is a transform. Rank/min/max/first/last/
        # index operations run on the codes (the latter group tracking a result
        # mask); any/all run on the boolean conversion. The compiled operator is
        # invoked with the missing mask. Operations on the no-cast list (rank
        # etc.) return the raw result; for first/last/min/max, positions masked
        # in the result are set to missing; the result is rebuilt as a
        # categorical with the same dtype.
        # KNOWN ISSUE: for index-of-min/max the result mask is created but only
        # first/last/min/max results are re-marked as missing; the index-of
        # operations rely on being in the cast blocklist.
        from pandas.core.groupby.ops import WrappedCythonOp

        kind = WrappedCythonOp.get_kind_from_how(how)
        op = WrappedCythonOp(how=how, kind=kind, has_dropped_na=has_dropped_na)

        dtype = self.dtype
        if how in ["sum", "prod", "cumsum", "cumprod", "skew", "kurt"]:
            raise TypeError(f"{dtype} type does not support {how} operations")
        if how in ["min", "max", "rank", "idxmin", "idxmax"] and not dtype.ordered:
            # raise TypeError instead of NotImplementedError to ensure we
            #  don't go down a group-by-group path, since in the empty-groups
            #  case that would fail to raise
            raise TypeError(f"Cannot perform {how} with non-ordered Categorical")
        if how not in [
            "rank",
            "any",
            "all",
            "first",
            "last",
            "min",
            "max",
            "idxmin",
            "idxmax",
        ]:
            if kind == "transform":
                raise TypeError(f"{dtype} type does not support {how} operations")
            raise TypeError(f"{dtype} dtype does not support aggregation '{how}'")

        result_mask = None
        mask = self.isna()
        if how == "rank":
            assert self.ordered  # checked earlier
            npvalues = self._ndarray
        elif how in ["first", "last", "min", "max", "idxmin", "idxmax"]:
            npvalues = self._ndarray
            result_mask = np.zeros(ngroups, dtype=bool)
        else:
            # any/all
            npvalues = self.astype(bool)

        res_values = op._cython_op_ndim_compat(
            npvalues,
            min_count=min_count,
            ngroups=ngroups,
            comp_ids=ids,
            mask=mask,
            result_mask=result_mask,
            **kwargs,
        )

        if how in op.cast_blocklist:
            return res_values
        elif how in ["first", "last", "min", "max"]:
            res_values[result_mask == 1] = -1
        return self._from_backing_data(res_values)


