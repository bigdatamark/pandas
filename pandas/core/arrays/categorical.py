    def value_counts(self, dropna: bool = True) -> Series:
        # [FUNCTION DOC]
        # Counts occurrences of each category. Parameter dropna (default true)
        # leaves missing values out; when false and any are present, an extra
        # final entry (keyed by the missing code) holds their count. Every
        # category gets an entry, including zero counts, in category order.
        # Returns a series of 64-bit integer counts named "count", indexed by a
        # categorical index over the categories.
        """
        Return a Series containing counts of each category.

        Every category will have an entry, even those with a count of 0.

        Parameters
        ----------
        dropna : bool, default True
            Don't include counts of NaN.

        Returns
        -------
        counts : Series

        See Also
        --------
        Series.value_counts
        """
        from pandas import (
            CategoricalIndex,
            Series,
        )

        code, cat = self._codes, self.categories
        ncat, mask = (len(cat), code >= 0)
        ix, clean = np.arange(ncat), mask.all()

        if dropna or clean:
            obs = code if clean else code[mask]
            count = np.bincount(obs, minlength=ncat or 0)
        else:
            count = np.bincount(np.where(mask, code, ncat))
            ix = np.append(ix, -1)

        ix = coerce_indexer_dtype(ix, self.dtype.categories)
        ix_categorical = self._from_backing_data(ix)

        return Series(
            count,
            index=CategoricalIndex(ix_categorical),
            dtype="int64",
            name="count",
            copy=False,
        )

