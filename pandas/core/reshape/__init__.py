# [PACKAGE DOC]
# Package holding the implementations of pandas reshaping operations: concatenation,
# merging and joining, pivoting, melting, dummy-variable encoding, stacking and
# unstacking, and binning of values into intervals.
# Submodules: api (public re-export surface), concat, encoding, melt, merge, pivot,
# reshape (stack/unstack machinery) and tile (cut and qcut binning).
# This package initializer is intentionally empty: it exports nothing itself and has no
# import-time side effects; users import the public functions from the api submodule or
# from the top-level pandas namespace.
