# [PACKAGE DOC]
# Package holding the Index class hierarchy used for axis labels in pandas
# objects. Submodules include the base index, numeric, range, multi-level,
# datetime-like (datetimes, timedeltas, periods), categorical, interval and
# frozen-list implementations, the accessors for datetime-like Series
# properties, and an api module that re-exports the public pieces and offers
# helpers to combine indexes.
# This initializer itself is empty: it defines and re-exports nothing and has
# no import-time side effects. Users must import from the specific
# submodules (the api module is the usual aggregation point).
